package net.paradisu.capture.core;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Properties;

/**
 * The few protocol facts the sniffer needs to follow state changes, generated by the dev CLI from Mojang's packet
 * report ({@code capture-protocol.properties}). Missing values are -1; the plugin then stops tracking the state after
 * login but still records packets.
 */
public final class ProtocolHints {
    public static final ProtocolHints NONE = new ProtocolHints(-1, -1, -1, -1, false);

    public final int protocol;
    public final int loginAcknowledged;
    public final int finishConfiguration;
    public final int configurationAcknowledged;
    public final boolean loaded;

    public ProtocolHints(
            int protocol,
            int loginAcknowledged,
            int finishConfiguration,
            int configurationAcknowledged,
            boolean loaded) {
        this.protocol = protocol;
        this.loginAcknowledged = loginAcknowledged;
        this.finishConfiguration = finishConfiguration;
        this.configurationAcknowledged = configurationAcknowledged;
        this.loaded = loaded;
    }

    /** Whether every value needed to follow the state machine is present. */
    public boolean complete() {
        return loaded
                && protocol >= 0
                && loginAcknowledged >= 0
                && finishConfiguration >= 0
                && configurationAcknowledged >= 0;
    }

    public static ProtocolHints load(String path) {
        if (path == null || path.isEmpty()) {
            return NONE;
        }
        Properties properties = new Properties();
        try (InputStream in = Files.newInputStream(Path.of(path))) {
            properties.load(in);
        } catch (IOException | RuntimeException e) {
            return NONE;
        }
        return new ProtocolHints(
                read(properties, "protocol"),
                read(properties, "login.serverbound.login_acknowledged"),
                read(properties, "configuration.serverbound.finish_configuration"),
                read(properties, "play.serverbound.configuration_acknowledged"),
                true);
    }

    private static int read(Properties properties, String key) {
        try {
            return Integer.parseInt(properties.getProperty(key, "-1").trim());
        } catch (NumberFormatException e) {
            return -1;
        }
    }
}
